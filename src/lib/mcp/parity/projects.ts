/** Portal settings without what lets a client in (the link token and the PIN): those never pass through a tool. */
function portalSettingsView(data: unknown): unknown {
  if (!data || typeof data !== 'object') return data;
  const { token: _token, pin: _pin, ...rest } = data as Record<string, unknown>;
  void _token; void _pin;
  return { ...rest, has_pin: typeof _pin === 'string' && _pin.length > 0 };
}

