-- 2.0: the app moves into its own schema, `pm`, so it can share a database
-- with a company's other apps. Every table, view, sequence and function of
-- the app moves from `public` and `communications` into `pm` with its data,
-- indexes, constraints, row security, triggers and realtime publication
-- (moving keeps each object's identity, so nothing pointing at it breaks).
-- Only the app's own objects move: the names are listed below, so anything
-- else in `public` (another app's tables) is left exactly as it is.
--
-- Also:
-- - function bodies and search paths that named `public` or `communications`
--   now name `pm`;
-- - scheduled jobs are renamed with a `pm-` prefix and the Vault entries for
--   webhook retries with `pm_`, so they cannot collide with another app's;
-- - an install's own schema `custom` moves into `pm_custom`;
-- - a bridge, for the few minutes the previous version may still be running
--   during a deploy: a view (security_invoker, so row security still applies)
--   in the old place for each moved table, and a wrapper for each function
--   the API may call. Marked 'pm-2.0 bridge'; 2.1 removes them. Realtime
--   subscriptions of the previous version go quiet until its tabs reload.
--
-- Breaking: 2.0 code reads `pm` only. Safe to run twice (a second run sees
-- the app already in `pm` and does nothing). Generated by
-- scripts/release/pm-schema.ts from the 1.11 schema; do not edit the lists
-- by hand.

