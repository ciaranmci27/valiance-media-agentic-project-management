BEGIN
  SET LOCAL lock_timeout = '5s';

  -- Already moved: nothing to do.
  IF to_regclass('pm.business_settings') IS NOT NULL THEN
    RAISE NOTICE 'The app is already in schema pm.';
    RETURN;
  END IF;

  CREATE SCHEMA IF NOT EXISTS pm;
  CREATE SCHEMA IF NOT EXISTS pm_custom;
  GRANT USAGE ON SCHEMA pm, pm_custom TO anon, authenticated, service_role;
  ALTER DEFAULT PRIVILEGES IN SCHEMA pm GRANT ALL ON TABLES TO anon, authenticated, service_role;
  ALTER DEFAULT PRIVILEGES IN SCHEMA pm GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
  ALTER DEFAULT PRIVILEGES IN SCHEMA pm GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;

  -- Preflight: nothing of the same name may already be in pm.
  FOREACH rel IN ARRAY app_relations LOOP
    IF to_regclass('pm.' || quote_ident(split_part(rel, '.', 2))) IS NOT NULL THEN
      RAISE EXCEPTION 'pm.% already exists: the move would collide with it. Nothing was changed.', split_part(rel, '.', 2);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_proc p WHERE p.pronamespace = 'pm'::regnamespace
             AND EXISTS (SELECT 1 FROM unnest(app_functions) AS fn WHERE split_part(fn, '.', 2) = p.proname)) THEN
    RAISE EXCEPTION 'A function of the app already exists in pm: the move would collide with it. Nothing was changed.';
  END IF;

  -- 1. Tables, views and sequences (owned sequences move with their tables).
  FOREACH rel IN ARRAY app_relations LOOP
    SELECT c.relkind INTO rel_kind FROM pg_class c WHERE c.oid = to_regclass(rel);
    CONTINUE WHEN rel_kind IS NULL;
    EXECUTE format('ALTER %s %s SET SCHEMA pm',
      CASE rel_kind WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' WHEN 'S' THEN 'SEQUENCE' ELSE 'TABLE' END,
      to_regclass(rel)::text);
  END LOOP;

  -- The runner's own table: no API role reads or writes it.
  IF to_regclass('pm.app_migrations') IS NOT NULL THEN
    REVOKE ALL ON pm.app_migrations FROM PUBLIC, anon, authenticated;
  END IF;

  -- 2. Functions, then their search paths and bodies.
  FOR f IN
    SELECT p.oid FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE (n.nspname || '.' || p.proname) = ANY (app_functions)
  LOOP
    EXECUTE format('ALTER FUNCTION %s SET SCHEMA pm', f.oid::regprocedure);
  END LOOP;

  FOR f IN
    SELECT p.oid, p.prosrc, p.proconfig FROM pg_proc p WHERE p.pronamespace = 'pm'::regnamespace
  LOOP
    IF f.proconfig && ARRAY['search_path=public', 'search_path=communications, public'] THEN
      EXECUTE format('ALTER FUNCTION %s SET search_path = pm', f.oid::regprocedure);
    END IF;
    IF f.prosrc ~ '\m(public|communications)\.(?!(read|manage)'')' OR f.prosrc ~ '''(public|communications)''' OR f.prosrc ~ '''webhook_scheduler_(url|secret)''' THEN
      def := pg_get_functiondef(f.oid);
      -- Not the permission names communications.read and communications.manage.
      def := regexp_replace(def, '\m(public|communications)\.(?!(read|manage)'')', 'pm.', 'g');
      def := regexp_replace(def, '''(public|communications)''', '''pm''', 'g');
      def := regexp_replace(def, '''webhook_scheduler_(url|secret)''', '''pm_webhook_scheduler_\1''', 'g');
      EXECUTE def;
    END IF;
  END LOOP;

  -- 3. Scheduled jobs and Vault entries, prefixed.
  IF to_regclass('cron.job') IS NOT NULL THEN
    FOR job IN
      SELECT jobid, jobname, schedule, command FROM cron.job
      WHERE jobname IN ('webhook-retries', 'billing-drafts', 'retainer-drafts', 'reminders-due')
    LOOP
      PERFORM cron.unschedule(job.jobid);
      PERFORM cron.schedule('pm-' || job.jobname, job.schedule,
        regexp_replace(job.command, '\m(public|communications)\.', 'pm.', 'g'));
    END LOOP;
  END IF;
  IF to_regclass('vault.secrets') IS NOT NULL THEN
    FOR secret IN SELECT id, name FROM vault.secrets WHERE name IN ('webhook_scheduler_url', 'webhook_scheduler_secret') LOOP
      PERFORM vault.update_secret(secret.id, NULL, 'pm_' || secret.name);
    END LOOP;
  END IF;

  -- 3b. Storage buckets, prefixed: each gets a pm- twin with the same settings
  -- and the same policies (named "pm: ..."). The old buckets and policies stay
  -- until 2.1, so links already sent keep working while files are copied
  -- across (npm run storage:copy-to-pm).
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    SELECT 'pm-' || b.id, 'pm-' || b.name, b.public, b.file_size_limit, b.allowed_mime_types
    FROM storage.buckets b WHERE b.id = ANY (app_buckets)
    ON CONFLICT (id) DO NOTHING;
    FOR f IN
      SELECT p.policyname, p.permissive, p.cmd, p.roles, p.qual, p.with_check FROM pg_policies p
      WHERE p.schemaname = 'storage' AND p.tablename = 'objects'
        AND coalesce(p.qual, '') || coalesce(p.with_check, '') ~ ('''(' || array_to_string(app_buckets, '|') || ')''')
        AND NOT EXISTS (SELECT 1 FROM pg_policies x WHERE x.schemaname = 'storage' AND x.tablename = 'objects' AND x.policyname = 'pm: ' || p.policyname)
    LOOP
      EXECUTE format('CREATE POLICY %I ON storage.objects AS %s FOR %s TO %s%s%s',
        'pm: ' || f.policyname, f.permissive, f.cmd,
        (SELECT string_agg(CASE WHEN r = 'public' THEN 'public' ELSE quote_ident(r) END, ', ') FROM unnest(f.roles) AS r),
        CASE WHEN f.qual IS NULL THEN '' ELSE ' USING (' || regexp_replace(f.qual, '''(' || array_to_string(app_buckets, '|') || ')''', '''pm-\1''', 'g') || ')' END,
        CASE WHEN f.with_check IS NULL THEN '' ELSE ' WITH CHECK (' || regexp_replace(f.with_check, '''(' || array_to_string(app_buckets, '|') || ')''', '''pm-\1''', 'g') || ')' END);
    END LOOP;
  END IF;

  -- 4. An install's own schema `custom` moves into `pm_custom`.
  IF to_regnamespace('custom') IS NOT NULL THEN
    FOR f IN
      SELECT c.oid, c.relkind FROM pg_class c
      WHERE c.relnamespace = 'custom'::regnamespace AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
        AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype IN ('a', 'i'))
    LOOP
      EXECUTE format('ALTER %s %s SET SCHEMA pm_custom',
        CASE f.relkind WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' WHEN 'f' THEN 'FOREIGN TABLE' ELSE 'TABLE' END,
        f.oid::regclass::text);
    END LOOP;
    FOR f IN SELECT c.oid FROM pg_class c WHERE c.relnamespace = 'custom'::regnamespace AND c.relkind = 'S' LOOP
      EXECUTE format('ALTER SEQUENCE %s SET SCHEMA pm_custom', f.oid::regclass::text);
    END LOOP;
    FOR f IN SELECT p.oid FROM pg_proc p WHERE p.pronamespace = 'custom'::regnamespace LOOP
      EXECUTE format('ALTER FUNCTION %s SET SCHEMA pm_custom', f.oid::regprocedure);
    END LOOP;
    FOR f IN SELECT t.oid FROM pg_type t WHERE t.typnamespace = 'custom'::regnamespace AND t.typtype IN ('e', 'c', 'd')
             AND NOT EXISTS (SELECT 1 FROM pg_class c WHERE c.reltype = t.oid) LOOP
      EXECUTE format('ALTER TYPE %s SET SCHEMA pm_custom', f.oid::regtype);
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relnamespace = 'custom'::regnamespace)
       AND NOT EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace = 'custom'::regnamespace) THEN
      DROP SCHEMA custom;
    END IF;
  END IF;

  -- 5. The bridge, for the previous version during a deploy.
  FOREACH rel IN ARRAY app_relations LOOP
    rel_schema := split_part(rel, '.', 1);
    rel_name := split_part(rel, '.', 2);
    CONTINUE WHEN rel_name = 'app_migrations';
    SELECT c.relkind INTO rel_kind FROM pg_class c WHERE c.oid = to_regclass('pm.' || quote_ident(rel_name));
    CONTINUE WHEN rel_kind IS NULL OR rel_kind = 'S';
    EXECUTE format('CREATE VIEW %I.%I WITH (security_invoker = true) AS SELECT * FROM pm.%I', rel_schema, rel_name, rel_name);
    EXECUTE format('COMMENT ON VIEW %I.%I IS %L', rel_schema, rel_name, 'pm-2.0 bridge');
    -- Only the grants the table had (not the old schema's defaults for new views).
    EXECUTE format('REVOKE ALL ON %I.%I FROM PUBLIC, anon, authenticated, service_role', rel_schema, rel_name);
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
      FOREACH priv IN ARRAY ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE'] LOOP
        IF has_table_privilege(role_name, format('pm.%I', rel_name), priv) THEN
          EXECUTE format('GRANT %s ON %I.%I TO %I', priv, rel_schema, rel_name, role_name);
        END IF;
      END LOOP;
    END LOOP;
  END LOOP;

  FOR f IN
    SELECT p.oid, p.proname, p.pronargs, p.proretset, p.provolatile, p.provariadic,
           split_part(fn, '.', 1) AS old_schema
    FROM pg_proc p
    JOIN unnest(app_functions) AS fn ON split_part(fn, '.', 2) = p.proname
    WHERE p.pronamespace = 'pm'::regnamespace
      AND p.prorettype NOT IN ('trigger'::regtype, 'event_trigger'::regtype)
      AND p.prokind = 'f'
      AND (has_function_privilege('anon', p.oid, 'EXECUTE')
        OR has_function_privilege('authenticated', p.oid, 'EXECUTE')
        OR has_function_privilege('service_role', p.oid, 'EXECUTE'))
  LOOP
    args := pg_get_function_arguments(f.oid);
    SELECT string_agg(CASE WHEN f.provariadic <> 0 AND i = f.pronargs THEN 'VARIADIC $' || i ELSE '$' || i END, ', ' ORDER BY i)
      INTO call_args FROM generate_series(1, f.pronargs) AS i;
    call_args := coalesce(call_args, '');
    IF f.proretset OR pg_get_function_result(f.oid) LIKE 'TABLE(%' THEN
      body := format('SELECT * FROM pm.%I(%s)', f.proname, call_args);
    ELSE
      body := format('SELECT pm.%I(%s)', f.proname, call_args);
    END IF;
    vol := CASE f.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END;
    EXECUTE format('CREATE FUNCTION %I.%I(%s) RETURNS %s LANGUAGE sql %s SECURITY INVOKER SET search_path = '''' AS %L',
      f.old_schema, f.proname, args, pg_get_function_result(f.oid), vol, body);
    EXECUTE format('COMMENT ON FUNCTION %I.%I(%s) IS %L', f.old_schema, f.proname, pg_get_function_identity_arguments(f.oid), 'pm-2.0 bridge');
    EXECUTE format('REVOKE ALL ON FUNCTION %I.%I(%s) FROM PUBLIC, anon, authenticated, service_role', f.old_schema, f.proname, pg_get_function_identity_arguments(f.oid));
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
      IF has_function_privilege(role_name, f.oid, 'EXECUTE') THEN
        EXECUTE format('GRANT EXECUTE ON FUNCTION %I.%I(%s) TO %I', f.old_schema, f.proname, pg_get_function_identity_arguments(f.oid), role_name);
      END IF;
    END LOOP;
  END LOOP;
END
